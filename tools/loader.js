#!/usr/bin/env node
/**
 * loader.js
 * ============================================================================
 * Keeps the loader files in step with their sources. Node only, no packages.
 *
 *   node tools/loader.js           write shared/kakao.css and the map in shared/kakao.js
 *   node tools/loader.js --check   exit 1 when either is out of date
 *
 * - shared/kakao.css   tokens.css, font.css, themes.css and base.css in one file, copied
 *                      unchanged (all four live in shared/, so font.css's
 *                      relative font URLs still hold).
 * - shared/kakao.js    the loader. Only its map, between the markers
 *                        / * @generated:start map … * /
 *                        / * @generated:end map * /
 *                      is generated: one line per tag from custom-elements.json
 *                      (each declaration's `kakao` field):
 *                        "kakao-toast": [script, [css…], [requires…], [enhancedBy…]]
 *                      The rest of kakao.js is written by hand.
 *
 * closure() is the dependency order the loader and tools/vendor.js share:
 * requires first, then enhancers, then the tag itself.
 * ============================================================================
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MANIFEST = 'custom-elements.json';
const CSS_OUT = 'shared/kakao.css';
const JS_OUT = 'shared/kakao.js';
const CSS_PARTS = ['shared/tokens.css', 'shared/font.css', 'shared/themes.css', 'shared/base.css'];
const START = /\/\* @generated:start map[^*]*\*\/\n/;
const END = '  /* @generated:end map */';

class LoaderError extends Error {}

/** tag -> { script, css, requires, enhancedBy }, in manifest order. */
function tagMap(manifest) {
  const map = new Map();
  for (const mod of manifest.modules || []) {
    for (const d of mod.declarations || []) {
      if (!d.tagName || !d.kakao) continue;
      const k = d.kakao;
      map.set(d.tagName, { script: k.script, css: k.css || [], requires: k.requires || [], enhancedBy: k.enhancedBy || [] });
    }
  }
  return map;
}

/** The tags `tags` need, dependencies first: requires, enhancers, the tag. */
function closure(map, tags) {
  const out = [];
  const seen = new Set();
  const visit = (t) => {
    if (seen.has(t) || !map.has(t)) return;
    seen.add(t);
    const k = map.get(t);
    k.requires.forEach(visit);
    k.enhancedBy.forEach(visit);
    out.push(t);
  };
  tags.forEach(visit);
  return out;
}

function css(root) {
  const head = [
    '/*',
    ' * kakao.css - tokens, font, themes and the page base in one file:',
    ' * shared/tokens.css, font.css, themes.css and base.css, unchanged, in that order.',
    ' * Generated by node tools/loader.js; edit the four sources, never this file.',
    ' * Pages that want only some of them link the single files instead.',
    ' */',
  ].join('\n');
  const parts = CSS_PARTS.map((f) => {
    const file = path.join(root, f);
    if (!fs.existsSync(file)) throw new LoaderError(`${f} is missing`);
    return `/* ---- ${f} ---- */\n${fs.readFileSync(file, 'utf8').trimEnd()}\n`;
  });
  return `${head}\n\n${parts.join('\n')}`;
}

function mapBlock(manifest) {
  const map = tagMap(manifest);
  const lines = [...map].map(([tag, k]) => `    ${JSON.stringify(tag)}: ${JSON.stringify([k.script, k.css, k.requires, k.enhancedBy])},`);
  return `  const MAP = {\n${lines.join('\n')}\n  };\n`;
}

function js(current, manifest) {
  const start = START.exec(current);
  const end = current.indexOf(END);
  if (!start || end < start.index) throw new LoaderError(`${JS_OUT} has no @generated:start map … @generated:end map markers`);
  return current.slice(0, start.index + start[0].length) + mapBlock(manifest) + current.slice(end);
}

function main(argv, root = ROOT) {
  let out;
  try {
    const manifest = JSON.parse(fs.readFileSync(path.join(root, MANIFEST), 'utf8'));
    const jsFile = path.join(root, JS_OUT);
    if (!fs.existsSync(jsFile)) throw new LoaderError(`${JS_OUT} is missing`);
    out = [
      [CSS_OUT, css(root)],
      [JS_OUT, js(fs.readFileSync(jsFile, 'utf8'), manifest)],
    ];
  } catch (e) {
    if (e instanceof LoaderError) {
      process.stderr.write(`loader: ${e.message}\n`);
      return 1;
    }
    throw e;
  }
  const read = (f) => (fs.existsSync(path.join(root, f)) ? fs.readFileSync(path.join(root, f), 'utf8') : null);
  if (argv.includes('--check')) {
    const stale = out.filter(([f, text]) => read(f) !== text).map(([f]) => f);
    if (!stale.length) {
      process.stdout.write(`${CSS_OUT} and the map in ${JS_OUT} are up to date.\n`);
      return 0;
    }
    process.stderr.write(`loader: ${stale.join(' and ')} out of date. Run node tools/loader.js.\n`);
    return 1;
  }
  for (const [f, text] of out) {
    if (read(f) !== text) fs.writeFileSync(path.join(root, f), text);
  }
  process.stdout.write(`Wrote ${CSS_OUT} and the map in ${JS_OUT}.\n`);
  return 0;
}

if (require.main === module) {
  const r = process.argv.indexOf('--root');
  process.exitCode = main(process.argv.slice(2), r > 0 ? path.resolve(process.argv[r + 1]) : ROOT);
}

module.exports = { tagMap, closure, css, js, mapBlock, main, CSS_PARTS, LoaderError };
